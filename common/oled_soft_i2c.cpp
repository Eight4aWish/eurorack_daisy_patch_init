static int CharToIndex(char c) {
    if (c >= 32 && c <= 122) return c - 32;
    return 0; // Space for unknown
}

uint8_t SSD1306::DrawChar(uint8_t x, uint8_t y, char c, bool invert) {
    int idx = CharToIndex(c);
    for (int col = 0; col < 5; col++) {
        uint8_t line = font5x7[idx][col];
        for (int row = 0; row < 7; row++) {
            bool on = (line >> row) & 1;
            if (invert) on = !on;
            SetPixel(x + col, y + row, on);
        }
    }
    // Clear space between characters
    for (int row = 0; row < 7; row++) {
        SetPixel(x + 5, y + row, invert);
    }
    return 6; // Character width + spacing
}

uint8_t SSD1306::DrawString(uint8_t x, uint8_t y, const char* str, bool invert) {
    uint8_t startX = x;
    while (*str) {
        x += DrawChar(x, y, *str, invert);
        str++;
    }
    return x - startX;
}

uint8_t SSD1306::DrawStringCentered(uint8_t y, const char* str, bool invert) {
    size_t len = strlen(str);
    uint8_t width = len * 6;
    uint8_t x = (OLED_WIDTH - width) / 2;
    return DrawString(x, y, str, invert);
}

uint8_t SSD1306::DrawCharLarge(uint8_t x, uint8_t y, char c, bool invert) {
    int idx = CharToIndex(c);
    for (int col = 0; col < 5; col++) {
        uint8_t line = font5x7[idx][col];
        for (int row = 0; row < 7; row++) {
            bool on = (line >> row) & 1;
            if (invert) on = !on;
            // Draw 2x2 pixels
            SetPixel(x + col * 2, y + row * 2, on);
            SetPixel(x + col * 2 + 1, y + row * 2, on);
            SetPixel(x + col * 2, y + row * 2 + 1, on);
            SetPixel(x + col * 2 + 1, y + row * 2 + 1, on);
        }
    }
    // Clear space between characters (2 pixels wide)
    for (int row = 0; row < 14; row++) {
        SetPixel(x + 10, y + row, invert);
        SetPixel(x + 11, y + row, invert);
    }
    return 12; // Character width (10) + spacing (2)
}

uint8_t SSD1306::DrawStringLarge(uint8_t x, uint8_t y, const char* str, bool invert) {
    uint8_t startX = x;
    while (*str) {
        x += DrawCharLarge(x, y, *str, invert);
        str++;
    }
    return x - startX;
}

uint8_t SSD1306::DrawStringLargeCentered(uint8_t y, const char* str, bool invert) {
    size_t len = strlen(str);
    uint8_t width = len * 12;
    int16_t x = (OLED_WIDTH - width) / 2;
    if (x < 0) x = 0;
    return DrawStringLarge(x, y, str, invert);
}

