#!/usr/bin/env python3
"""
gru_to_header.py — compile train_gru.py runs into the firmware as .grnb bytes, for the
GRU test build (src/gru_test.cpp), which needs no card. The firmware parses them with
gru::Parse(), the same CRC-checked path a card file will take.

    .venv-nam/bin/python tools/gru_to_header.py nam/gru_test_nets.h \\
        "captures/wasp/gru_runs/lp_cr_gru24_s2:WASP CR24" "captures/wasp/gru_runs/lp6_c_gru24_s2:WASP C24"
"""

import argparse
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from gru_export import export  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("out", help="the header to write")
    ap.add_argument("runs", nargs="+", help="run_folder:NAME, in the order the firmware cycles them")
    args = ap.parse_args()
    lines = ["#pragma once", "// Generated by tools/gru_to_header.py: do not edit. Each entry is a whole .grnb file.",
             "#include <cstddef>", "#include <cstdint>", "", "namespace gru_nets", "{", ""]
    names = []
    for i, spec in enumerate(args.runs):
        folder, _, name = spec.rpartition(":")
        data = export(pathlib.Path(folder), name)
        lines.append(f"// {pathlib.Path(folder).name}: '{name}', {len(data)} bytes")
        lines.append(f"inline const uint8_t kNet{i}[] = {{")
        for k in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[k:k + 16]) + ",")
        lines.append("};")
        names.append(i)
    lines += ["", "struct Blob", "{", "    const uint8_t* data;", "    size_t         size;", "};",
              f"inline constexpr int kCount = {len(names)};",
              "inline const Blob kNets[kCount] = {" + ", ".join(f"{{kNet{i}, sizeof(kNet{i})}}" for i in names) + "};",
              "", "} // namespace gru_nets", ""]
    pathlib.Path(args.out).write_text("\n".join(lines))
    print(f"{args.out}: {len(names)} networks")


if __name__ == "__main__":
    main()
